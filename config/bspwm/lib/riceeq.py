# mpv, MPD...): a PipeWire filter-chain run as its own small process
# (`pipewire -c rice-eq.conf`, the user unit rice-eq.service). It is a
# WirePlumber "smart filter": inserted in front of the default output by
# itself, the default device stays the same, and stopping it puts the
# sound back as it was. Gains change live (pw-cli set-param), no restart.
#
# State: ~/.config/bspwm/config/eq.json  {"on": bool, "preset": str, "gains": [10 dB]}
